-- ─────────────────────────────────────────────────────────────
-- 고객사 포털을 위한 user_role 확장: 'admin' | 'staff' → + 'client'
-- 이 문장은 반드시 단독으로 실행해야 한다. Postgres는 새로 추가한 enum 값을
-- 같은 트랜잭션/스크립트 안에서 곧바로 참조(체크 제약, 정책, 컬럼 기본값 등)하는 것을
-- 허용하지 않는다. 이 파일 실행 후 정상 완료를 확인한 뒤 0007을 실행할 것.
-- ─────────────────────────────────────────────────────────────

alter type user_role add value 'client';
